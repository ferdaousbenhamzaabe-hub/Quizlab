# 🎓 LabQuiz

**Apprends · Joue · Progresse**

LabQuiz est une application web interactive qui permet de tester ses connaissances grâce à des quiz à choix multiples. Elle propose une interface moderne, un thème clair/sombre et la possibilité de personnaliser les questions.

## ✨ Fonctionnalités

- 🧠 Jouer à des quiz avec des questions à choix multiples.
- ✅ Obtenir son score et consulter les explications des réponses.
- ✏️ Ajouter et supprimer des questions personnalisées.
- 💾 Sauvegarder les questions personnalisées dans le navigateur grâce à `localStorage`.
- 🌙 Basculer entre le thème clair et le thème sombre.
- 📱 Profiter d’une interface responsive.

## 🛠️ Technologies utilisées

- HTML5
- CSS3
- JavaScript (Vanilla JS)
- LocalStorage

