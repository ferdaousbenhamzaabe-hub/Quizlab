## 🚀 Installation et lancement

1. Clone le dépôt :

   ```bash
   git clone https://github.com/ferdaousbenhamzaabe-hub/Quizlab.git
   ```

2. Entre dans le dossier du projet :

   ```bash
   cd Quizlab
   ```

3. Ouvre `quizlab.html` dans ton navigateur.

Tu peux également utiliser l’extension Live Server de Visual Studio Code pour lancer l’application.

Aucune installation de dépendances n’est nécessaire.

## 🎮 Utilisation

1. Clique sur **Jouer** pour commencer un quiz.
2. Réponds aux questions et consulte ton score.
3. Accède à **Mes Questions** pour personnaliser ton quiz.
4. Utilise le bouton de thème pour passer du mode clair au mode sombre.

## 🎯 Objectif du projet

Ce projet permet de pratiquer le développement web front-end, notamment la manipulation du DOM, les événements JavaScript, le stockage local et la création d’une interface responsive.

